def watch_model_folder():
   """Monitors the /model directory for file modifications."""
   # Get the absolute path to the 'model' folder inside this add-on directory
   addon_dir = os.path.dirname(__file__)
   model_dir = os.path.join(addon_dir, "model")
   
   if not os.path.isdir(model_dir):
      return

   # Helper function to get the maximum modification time of files in the folder
   def get_latest_mtime():
      max_mtime = 0
      for root, _, files in os.walk(model_dir):
         for file in files:
            file_path = os.path.join(root, file)
            try:
                  mtime = os.path.getmtime(file_path)
                  max_mtime = max(max_mtime, mtime)
            except (FileNotFoundError, PermissionError):
                  continue
      return max_mtime

   # Initialize the last known modification time
   last_mtime = get_latest_mtime()

   while True:
      # Prevent high CPU usage by polling every 2 seconds
      time.sleep(3)
      
      current_mtime = get_latest_mtime()
      if current_mtime > last_mtime:
         last_mtime = current_mtime
         
         # Use Anki's main thread wrapper to safely execute UI or database operations
         mw.taskman.run_on_main(prep_model)


