def resize_and_center_anki():
   w = int(CONFIG['window']['width'])
   h = int(CONFIG['window']['height'])
   aspect = CONFIG['window']['aspect']
 
   if aspect != '':
      wa, ha = map(int, aspect.split(":"))
      h = int(w * ha / wa)

   screen = mw.screen()
   if not screen:
      return
   screen_geo = screen.geometry()

   x = screen_geo.x() + (screen_geo.width() - w) // 2
   y = screen_geo.y() + (screen_geo.height() - h) // 2
 
   mw.setGeometry(x, y, w, h)


def setup_menu():
   menu_items = [
      ("Generate Deck", wrapper),
      ("Update Model", prep_model),
      ("Center Window", resize_and_center_anki),
      ("Edit Config...", edit_config),
   ]

   kanji_menu = None
   for action in mw.form.menuTools.actions():
      if action.text() == "Yuzutan" and action.menu():
            kanji_menu = action.menu()
            break

   if not kanji_menu:
      kanji_menu = QMenu("Yuzutan", mw)
      mw.form.menuTools.addMenu(kanji_menu)

   kanji_menu.clear()

   for label, callback in menu_items:
      if label == "Edit Config...":
            kanji_menu.addSeparator()
            
      action = QAction(label, mw)
      action.triggered.connect(callback)
      kanji_menu.addAction(action)

setup_menu()
















